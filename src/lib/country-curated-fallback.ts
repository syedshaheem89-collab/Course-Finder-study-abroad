export function getCuratedFallbackCourses(params: {
  country: string;
  targetLevel?: string;
  coursePreference?: string;
  budgetEur?: number;
  twelfthPercent?: number;
  bachelorPercent?: number;
  effectiveIelts?: number;
  hasMoi?: boolean;
  backlogs?: number;
  sector?: SectorFilter;
  priorityUniversities?: PriorityUniversityRule[];
  maxResults?: number;
}) {
  const targetCountry = params.country.trim();
  const maxResults = Math.min(20, Math.max(6, params.maxResults ?? 12));
  const sectorFilter: SectorFilter = params.sector || 'all';
  const priorityRules = params.priorityUniversities || [];

  const key = Object.keys(CURATED_CATALOG).find(
    (k) => k.toLowerCase() === targetCountry.toLowerCase()
  );

  let seeds: CuratedSeedCourse[] = key ? [...CURATED_CATALOG[key]] : [];

  // Supplement with generic real-structured university programmes when curated catalog has fewer than maxResults
  if (seeds.length === 0) {
    seeds = buildGenericCountrySeeds(
      targetCountry,
      params.targetLevel,
      params.coursePreference,
      params.budgetEur
    );
  } else if (seeds.length < maxResults) {
    const extras = buildGenericCountrySeeds(
      targetCountry,
      params.targetLevel,
      params.coursePreference,
      params.budgetEur
    );
    const seen = new Set(seeds.map((s) => `${s.university_name}::${s.program_name}`.toLowerCase()));
    for (const ex of extras) {
      if (seeds.length >= maxResults + 2) break;
      const k = `${ex.university_name}::${ex.program_name}`.toLowerCase();
      if (!seen.has(k)) {
        seen.add(k);
        seeds.push(ex);
      }
    }
  }

  // Also ensure any Admin priority universities configured for this country appear as selectable options if missing
  if (priorityRules.length > 0) {
    const intel = getCountryVisaIntel(targetCountry, params.targetLevel);
    const subj = params.coursePreference || 'International Business & Technology';
    const lvl = params.targetLevel || 'Master';
    const countryPrios = priorityRules.filter(
      (r) => r.country.toLowerCase() === targetCountry.toLowerCase()
    );
    for (const prio of countryPrios) {
      const alreadyExists = seeds.some((s) =>
        s.university_name.toLowerCase().includes(prio.university_name.toLowerCase()) ||
        prio.university_name.toLowerCase().includes(s.university_name.toLowerCase())
      );
      if (!alreadyExists) {
        const sector = classifyUniversityType(
          prio.university_name,
          prio.country,
          undefined,
          priorityRules
        );
        seeds.unshift({
          program_name: `${lvl.toLowerCase().includes('bachelor') ? 'BSc (Hons)' : 'MSc'} in ${subj}`,
          university_name: prio.university_name,
          country: targetCountry,
          degree_level: lvl.toLowerCase().includes('bachelor') ? 'Bachelor' : 'Master',
          category: subj,
          institution_type: sector,
          tuition_fees_eur: params.budgetEur && params.budgetEur > 0 ? Math.min(params.budgetEur, 16000) : 14500,
          duration_months: lvl.toLowerCase().includes('bachelor') ? 36 : 18,
          intake_months: ['September', 'January'],
          stay_back_visa_years: intel.stayBackYears,
          average_graduate_salary: intel.avgSalaryEur,
          min_12th_percent: 55,
          min_degree_percent: 55,
          min_ielts: 6.0,
          english_policy: 'MOI_ACCEPTED',
          course_url: `https://www.google.com/search?q=${encodeURIComponent(`${prio.university_name} ${subj} ${targetCountry}`)}`,
        });
      }
    }
  }

  const enriched = seeds
    .map((s) => {
      const resolvedSector: UniversitySector =
        s.institution_type ||
        classifyUniversityType(s.university_name, s.country, undefined, priorityRules);
      const prioMatch = getPriorityUniversityMatch(s.university_name, s.country, priorityRules);
      const effectiveSector: UniversitySector =
        prioMatch.rule?.sector_override === 'Public' ||
        prioMatch.rule?.sector_override === 'Private'
          ? prioMatch.rule.sector_override
          : resolvedSector;
      return { s, sector: effectiveSector, prioMatch };
    })
    .filter((entry) => sectorFilter === 'all' || entry.sector === sectorFilter);

  const scored = enriched.map(({ s, sector, prioMatch }) => {
    let score = 78;
    const lowerLevel = (params.targetLevel || '').toLowerCase();
    const sDeg = s.degree_level.toLowerCase();

    if (lowerLevel) {
      if (lowerLevel.includes('mba') && (sDeg.includes('mba') || s.program_name.toLowerCase().includes('mba'))) {
        score += 12;
      } else if (lowerLevel.includes('undergraduate') && sDeg.includes('bachelor')) {
        score += 12;
      } else if ((lowerLevel.includes('master') || lowerLevel.includes('phd')) && sDeg.includes('master')) {
        score += 10;
      } else if (lowerLevel.includes('pg diploma') && sDeg.includes('diploma')) {
        score += 10;
      } else {
        score -= 10;
      }
    }

    if (params.coursePreference) {
      const tokens = params.coursePreference.toLowerCase().split(/\s+/).filter((t) => t.length >= 2);
      const hay = `${s.program_name} ${s.category}`.toLowerCase();
      if (tokens.some((t) => hay.includes(t))) score += 14;
    }

    if (params.budgetEur && params.budgetEur > 0) {
      if (s.tuition_fees_eur <= params.budgetEur) score += 8;
      else if (s.tuition_fees_eur > params.budgetEur * 1.4) score -= 14;
    }

    const activeMark =
      sDeg.includes('bachelor')
        ? params.twelfthPercent
        : params.bachelorPercent ?? params.twelfthPercent;
    if (activeMark !== undefined) {
      score += activeMark >= s.min_degree_percent ? 6 : -8;
    }

    if (params.hasMoi && s.english_policy === 'MOI_ACCEPTED') {
      score += 6;
    } else if (params.effectiveIelts && params.effectiveIelts > 0) {
      score += params.effectiveIelts >= s.min_ielts ? 5 : -8;
    }

    if ((params.backlogs || 0) > 4) score -= 6;
    if (prioMatch.isPriority) score += 12;

    const matchScore = Math.min(98, Math.max(54, score));
    const admissionChance: 'High' | 'Good' | 'Stretch' =
      matchScore >= 82 ? 'High' : matchScore >= 68 ? 'Good' : 'Stretch';

    const reasonParts: string[] = [
      `${s.university_name} (${sector} · ${s.country}) offers ${s.degree_level} tuition around €${s.tuition_fees_eur.toLocaleString()}/yr`,
    ];
    if (params.budgetEur && params.budgetEur > 0 && s.tuition_fees_eur <= params.budgetEur) {
      reasonParts.push(`fits within your €${params.budgetEur.toLocaleString()} budget`);
    }
    if (params.hasMoi && s.english_policy === 'MOI_ACCEPTED') {
      reasonParts.push('accepts MOI waiver');
    } else {
      reasonParts.push(`requires IELTS ${s.min_ielts}`);
    }
    const why = `${reasonParts.join(', ')} with ${s.stay_back_visa_years >= 1 ? `${s.stay_back_visa_years} yr` : `${Math.round(s.stay_back_visa_years * 12)} mo`} post-study stay-back.`;
    const roiRatio = Number(((s.average_graduate_salary / (Math.max(s.tuition_fees_eur, 2000) + 12000)) * 2.5).toFixed(1));

    return {
      course_id: `curated-${s.country.toLowerCase().replace(/\s+/g, '-')}-${s.university_name.slice(0, 12).toLowerCase().replace(/[^a-z0-9]/g, '')}-${s.program_name.slice(0, 10).toLowerCase().replace(/[^a-z0-9]/g, '')}`,
      program_name: s.program_name,
      university_name: s.university_name,
      country: s.country,
      degree_level: s.degree_level,
      category: s.category,
      institution_type: sector,
      is_priority_university: prioMatch.isPriority,
      priority_rank: prioMatch.isPriority ? prioMatch.rank : null,
      tuition_fees_eur: s.tuition_fees_eur,
      duration_months: s.duration_months,
      intake_months: s.intake_months,
      stay_back_visa_years: s.stay_back_visa_years,
      average_graduate_salary: s.average_graduate_salary,
      min_12th_percent: s.min_12th_percent,
      min_degree_percent: s.min_degree_percent,
      min_ielts: s.min_ielts,
      english_policy: s.english_policy,
      match_score: matchScore,
      fit_score: matchScore,
      admission_chance: admissionChance,
      why_it_fits: why,
      rationale: why,
      course_url: s.course_url,
      is_verified_db: false,
      roi_ratio: Math.max(roiRatio, 2.5),
      settlement_probability_percent: Math.min(95, Math.max(70, matchScore)),
      _priorityRankSort: prioMatch.isPriority ? prioMatch.rank : 9999,
    };
  });

  scored.sort((a, b) => {
    const pDiff = (a.is_priority_university ? 0 : 1) - (b.is_priority_university ? 0 : 1);
    if (pDiff !== 0) return pDiff;
    if (a.is_priority_university && b.is_priority_university && a._priorityRankSort !== b._priorityRankSort) {
      return a._priorityRankSort - b._priorityRankSort;
    }
    return b.match_score - a.match_score;
  });

  return scored.slice(0, maxResults).map(({ _priorityRankSort, ...rest }) => rest);
}
